-- Recuperación de contraseña con un código de un solo uso. El código se guarda con hash (BCrypt),
-- nunca en texto plano. cerrada_en marca que el pedido ya no sirve: se usó, se anuló porque se
-- pidió otro código o se agotaron los intentos.

create table recuperacion_password (
    id           bigint generated by default as identity primary key,
    usuario_id   bigint       not null references usuario (id),
    codigo_hash  varchar(100) not null,
    creada_en    timestamptz  not null,
    vence_en     timestamptz  not null,
    cerrada_en   timestamptz,
    intentos     integer      not null default 0,
    constraint ck_recuperacion_vencimiento check (vence_en > creada_en),
    constraint ck_recuperacion_intentos check (intentos >= 0)
);

create index ix_recuperacion_usuario_abierta on recuperacion_password (usuario_id)
    where cerrada_en is null;
