-- Esquema inicial. Una migración aplicada no se edita: cualquier cambio va en una versión nueva.
-- Ninguna clave foránea borra en cascada: las bajas son lógicas y el historial no se pierde.

create table usuario (
    id               bigint generated by default as identity primary key,
    username         varchar(50)  not null,
    nombre_completo  varchar(100) not null,
    password_hash    varchar(100) not null,
    rol              varchar(20)  not null,
    activo           boolean      not null default true,
    creado_en        timestamptz  not null,
    constraint uq_usuario_username unique (username),
    constraint ck_usuario_rol check (rol in ('ADMIN', 'FARMACEUTICO', 'CONSULTA'))
);

create table proveedor (
    id            bigint generated by default as identity primary key,
    razon_social  varchar(150) not null,
    cuit          varchar(11)  not null,
    telefono      varchar(30),
    email         varchar(120),
    activo        boolean      not null default true,
    constraint uq_proveedor_cuit unique (cuit),
    constraint ck_proveedor_cuit check (cuit ~ '^[0-9]{11}$')
);

create table area (
    id      bigint generated by default as identity primary key,
    nombre  varchar(80) not null,
    activo  boolean     not null default true
);

create unique index ux_area_nombre on area (lower(nombre));

create table medicamento (
    id            bigint generated by default as identity primary key,
    codigo        varchar(30)  not null,
    nombre        varchar(120) not null,
    presentacion  varchar(120) not null,
    stock_minimo  integer      not null,
    activo        boolean      not null default true,
    constraint uq_medicamento_codigo unique (codigo),
    constraint ck_medicamento_stock_minimo check (stock_minimo >= 0)
);

create table lote (
    id                 bigint generated by default as identity primary key,
    medicamento_id     bigint      not null references medicamento (id),
    proveedor_id       bigint      not null references proveedor (id),
    numero_lote        varchar(50) not null,
    fecha_vencimiento  date        not null,
    cantidad_inicial   integer     not null,
    cantidad_actual    integer     not null,
    fecha_ingreso      date        not null,
    registrado_por_id  bigint      not null references usuario (id),
    creado_en          timestamptz not null,
    constraint uq_lote_medicamento_numero unique (medicamento_id, numero_lote),
    constraint ck_lote_cantidad_inicial check (cantidad_inicial > 0),
    constraint ck_lote_cantidad_actual check (cantidad_actual >= 0 and cantidad_actual <= cantidad_inicial)
);

create index ix_lote_medicamento_vencimiento on lote (medicamento_id, fecha_vencimiento);
-- Índice parcial para las alertas: solo interesan los lotes con stock.
create index ix_lote_vencimiento_con_stock on lote (fecha_vencimiento) where cantidad_actual > 0;
create index ix_lote_proveedor on lote (proveedor_id);

create table transferencia (
    id                bigint generated by default as identity primary key,
    fecha_hora        timestamptz  not null,
    area_id           bigint       not null references area (id),
    realizada_por_id  bigint       not null references usuario (id),
    observaciones     varchar(500)
);

create index ix_transferencia_fecha_hora on transferencia (fecha_hora);
create index ix_transferencia_area on transferencia (area_id);

create table detalle_transferencia (
    id                bigint generated by default as identity primary key,
    transferencia_id  bigint  not null references transferencia (id),
    lote_id           bigint  not null references lote (id),
    cantidad          integer not null,
    constraint ck_detalle_cantidad check (cantidad > 0)
);

create index ix_detalle_transferencia on detalle_transferencia (transferencia_id);
create index ix_detalle_lote on detalle_transferencia (lote_id);

create table movimiento_stock (
    id                bigint generated by default as identity primary key,
    lote_id           bigint       not null references lote (id),
    tipo              varchar(20)  not null,
    cantidad          integer      not null,
    saldo_resultante  integer      not null,
    fecha_hora        timestamptz  not null,
    usuario_id        bigint       not null references usuario (id),
    transferencia_id  bigint       references transferencia (id),
    motivo            varchar(200),
    constraint ck_movimiento_tipo check (tipo in ('INGRESO', 'EGRESO', 'BAJA_VENCIMIENTO', 'AJUSTE')),
    constraint ck_movimiento_cantidad check (cantidad <> 0),
    constraint ck_movimiento_saldo check (saldo_resultante >= 0)
);

create index ix_movimiento_lote_fecha on movimiento_stock (lote_id, fecha_hora);
create index ix_movimiento_transferencia on movimiento_stock (transferencia_id);
create index ix_movimiento_fecha on movimiento_stock (fecha_hora);
